'use strict';
// Pure source-data checks; no real microphone, network, export, or DSP writes.
const assert=require('node:assert/strict');
const {analyze}=require('../mixer-vocal-preflight.js');
const rate=44100,n=rate,twopi=2*Math.PI;
function wave(amplitude=.25,freq=220){
 const samples=new Float32Array(n);
 for(let i=0;i<n;i++)samples[i]=amplitude*Math.sin(twopi*freq*i/rate);
 return samples;
}
const left=wave(),leftCopy=left.slice();
const standard=analyze([left],rate);
assert.equal(standard.frames,rate);
assert.equal(standard.channels,1);
assert(Math.abs(standard.metrics.peakDbfs-20*Math.log10(.25))<.01);
assert(Math.abs(standard.metrics.rmsDbfs-20*Math.log10(.25/Math.sqrt(2)))<.01);
assert.equal(standard.metrics.stereoCorrelation,null);
assert.deepEqual(standard.warnings,[]);
assert.deepEqual(left,leftCopy,'Source must remain bit-exact');
const opposed=Float32Array.from(left,x=>-x);
const phase=analyze([left,opposed],rate);
assert(phase.metrics.stereoCorrelation<-.999999);
assert(phase.warnings.some(x=>x.id==='stereo_antiphase'));
assert.deepEqual(opposed,Float32Array.from(left,x=>-x),'No source changes');
const weak=Float32Array.from(left,x=>x*.05);
const imbalance=analyze([left,weak],rate);
assert(imbalance.warnings.some(x=>x.id==='stereo_imbalance'));
assert(!imbalance.warnings.some(x=>x.id==='stereo_antiphase'));
const dc=Float32Array.from(left,x=>x+.06);
const offset=analyze([dc],rate);
assert(offset.metrics.dcOffset[0]>.059);
assert(offset.warnings.some(x=>x.id==='dc_offset'));
const quiet=wave(.00005);
assert(analyze([quiet],rate).warnings.some(x=>x.id==='very_low_level'));
const clipped=left.slice();
clipped[100]=1;clipped[101]=-1;
const danger=analyze([clipped],rate);
assert.equal(danger.metrics.nearFullScaleSamples,2);
assert(danger.warnings.some(x=>x.id==='possible_digital_clipping'));
const near=left.slice();near[100]=.96;
const caution=analyze([near],rate);
assert(caution.warnings.some(x=>x.id==='little_peak_headroom'));
assert(!caution.warnings.some(x=>x.id==='possible_digital_clipping'));
assert.throws(()=>analyze([left,opposed.subarray(1)],rate),/Canales incompatibles/);
assert.throws(()=>analyze([left],0),/Frecuencia de muestreo/);
assert.throws(()=>analyze([left,left,left],rate),/mono o estéreo/);
const invalid=left.slice();invalid[20]=NaN;
assert.throws(()=>analyze([invalid],rate),/no finita/);
const beyond=left.slice();beyond[20]=1.5;
assert.throws(()=>analyze([beyond],rate),/fuera de escala/);
assert.throws(()=>analyze([new Float32Array(0)],rate),/duración excesiva/);
console.log('PASS source vocal preflight: RMS/peak, DC, silent/near-full-scale, stereo phase/balance, immutable PCM and strict validation.');
