'use strict';
const assert=require('node:assert/strict');
const preflight=require('../mixer-export-preflight.js');
const MiB=preflight.MiB;
const small=preflight.estimate({frames:44100,rate:44100,bits:16,kind:'master'});
assert.equal(small.wavBytes,44+44100*4);
assert.equal(small.durationSeconds,1);
assert.equal(small.auditWithinLimit,true);
assert.deepEqual(small.warnings,[]);
const long=preflight.estimate({frames:48000*300,rate:48000,bits:24,kind:'master',audit:true});
assert.equal(long.wavBytes,44+48000*300*6);
assert.equal(long.auditWithinLimit,false);
assert(long.warnings.some(x=>x.includes('auditoría PCM exacta')));
assert(long.warnings.some(x=>x.includes('Reserva mínima')));
assert(long.minimumWorkingBytes>long.wavBytes);
const longNoAudit=preflight.estimate({frames:48000*300,rate:48000,bits:24,kind:'master',audit:false});
assert(longNoAudit.minimumWorkingBytes<long.minimumWorkingBytes);
assert(!longNoAudit.warnings.some(x=>x.includes('auditoría PCM exacta')));
const permitted=preflight.estimate({frames:48000*60,rate:48000,bits:16,kind:'stems',stemCount:8});
assert.equal(permitted.zipUpperBound,8*(44+48000*60*4)+10240);
assert(permitted.zipUpperBound<145*MiB);
assert(permitted.warnings.length>0,'Large multitrack sessions should trigger a memory advisory');
const single=preflight.estimate({frames:48000*60,rate:48000,bits:24,kind:'stem'});
assert.equal(single.zipUpperBound,null);
assert(single.summary.includes('Stem WAV PCM24'));
assert.throws(()=>preflight.estimate({frames:48000*100,rate:48000,bits:24,kind:'stems',stemCount:8}),/ZIP de stems superaría 145 MB/);
assert.throws(()=>preflight.estimate({frames:48000*600,rate:48000,bits:24,kind:'stem'}),/La pista excede/);
assert.throws(()=>preflight.estimate({frames:48000*600,rate:48000,bits:24,kind:'master'}),/duración supera/);
for(const frames of [0,-1,1.5,NaN,Infinity,2147483648])assert.throws(()=>preflight.estimate({frames,rate:44100,bits:16}),/Duración/);
for(const rate of [0,44101,'48000',96000])assert.throws(()=>preflight.estimate({frames:44100,rate,bits:16}),/Frecuencia/);
for(const bits of [0,32,'24'])assert.throws(()=>preflight.estimate({frames:44100,rate:44100,bits}),/Profundidad/);
for(const kind of ['archive','other',null])assert.throws(()=>preflight.estimate({frames:44100,rate:44100,bits:16,kind}),/Formato/);
for(const stemCount of [0,9,.2])assert.throws(()=>preflight.estimate({frames:44100,rate:44100,bits:16,stemCount}),/Número/);
assert.throws(()=>preflight.estimate({frames:44100,rate:44100,bits:16,audit:'yes'}),/auditoría/);
console.log('PASS export preflight: 60–600s plans, byte-exact PCM/ZIP, audit and RAM advisories, strict early safety limits.');
