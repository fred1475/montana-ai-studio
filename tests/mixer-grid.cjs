"use strict";
const assert=require("node:assert/strict"),fs=require("node:fs"),path=require("node:path");
const {chromium}=require("playwright");
const rate=44100,n=rate;
const wave=Buffer.alloc(44+n*2);
wave.write("RIFF",0);wave.writeUInt32LE(wave.length-8,4);wave.write("WAVE",8);
wave.write("fmt ",12);wave.writeUInt32LE(16,16);wave.writeUInt16LE(1,20);wave.writeUInt16LE(1,22);
wave.writeUInt32LE(rate,24);wave.writeUInt32LE(rate*2,28);wave.writeUInt16LE(2,32);wave.writeUInt16LE(16,34);
wave.write("data",36);wave.writeUInt32LE(n*2,40);
for(let i=0;i<n;i++)wave.writeInt16LE(Math.round(13000*Math.sin(2*Math.PI*220*i/rate)),44+i*2);
(async()=>{
 const browser=await chromium.launch({headless:true});
 try{
  const page=await browser.newPage({acceptDownloads:true}),errors=[];
  page.on("pageerror",e=>errors.push(e.message));
  await page.goto("http://127.0.0.1:8765/mixer-8.html");
  assert.equal(await page.locator("#gridSnapOn").isChecked(),false,"Grid snap opt-in");
  assert.equal(await page.locator("#gridDivision").isDisabled(),true);
  await page.locator("#bpm").fill("120");
  await page.locator("#file1").setInputFiles({name:"grid-tone.wav",mimeType:"audio/wav",buffer:wave});
  await page.waitForFunction(()=>document.querySelector("#label1")?.textContent?.includes("grid-tone"));
  await page.locator("#copyDetails1 summary").click();
  await page.locator("#copyAt1").fill("1.08");
  await page.locator("#copyPaste1").click();
  assert.equal(await page.locator("#copyOffset0_1").inputValue(),"1.08","Snap off preserves manual paste time");
  await page.locator("#copyRemove1").click();
  await page.locator("#gridSnapOn").check();
  assert.equal(await page.locator("#gridDivision").isDisabled(),false);
  await page.locator("#gridDivision").selectOption("16");
  assert(Math.abs(await page.evaluate(()=>gridSnapTime(1.08))-1.125)<1e-7,"At 120 BPM sixteenth note is .125s");
  assert(Math.abs(await page.evaluate(()=>gridSnapTime(1.19))-1.25)<1e-7);
  await page.locator("#copyPaste1").click();
  assert.equal(await page.locator("#copyOffset0_1").inputValue(),"1.125","New paste quantized to nearest sixteenth");
  const clip=page.locator('#timeline [data-track="1"][data-part="2"]');
  await clip.focus();
  await clip.press("ArrowRight");
  assert.equal(await page.locator("#copyOffset0_1").inputValue(),"1.25","Keyboard move advances one sixteenth");
  await page.locator("#undoEdit").click();
  assert.equal(await page.locator("#copyOffset0_1").inputValue(),"1.125");
  await page.locator("#redoEdit").click();
  assert.equal(await page.locator("#copyOffset0_1").inputValue(),"1.25");
  await page.locator("#gridDivision").selectOption("8");
  assert(Math.abs(await page.evaluate(()=>gridSnapTime(1.13))-1.25)<1e-7,"Eighth notes at 120 BPM are .25 s");
  await page.locator("#bpm").fill("90");
  assert(Math.abs(await page.evaluate(()=>gridSnapTime(.99))-1)<1e-4,"Grid recalculates correctly after BPM change");
  assert((await page.locator("#gridStatus").innerText()).includes("90 BPM"));
  const [savedDownload]=await Promise.all([page.waitForEvent("download"),page.locator("#saveSession").click()]);
  const savedPath=path.join(process.cwd(),"grid-project.json");await savedDownload.saveAs(savedPath);
  const project=JSON.parse(fs.readFileSync(savedPath,"utf8"));
  assert.equal(project.gridSnapOn,true);assert.equal(project.gridDivision,8);
  assert.equal(project.tracks[1].clipCopies.copies[0].offset,1.25);
  await page.reload();
  await page.locator("#sessionFile").setInputFiles(savedPath);
  await page.waitForFunction(()=>document.querySelector("#status")?.textContent?.includes("Sesión restaurada"));
  assert.equal(await page.locator("#bpm").inputValue(),"90");
  assert.equal(await page.locator("#gridSnapOn").isChecked(),true);
  assert.equal(await page.locator("#gridDivision").inputValue(),"8");
  assert.equal(await page.locator("#copyOffset0_1").inputValue(),"1.25","No retrospective quantization on restore");
  project.gridDivision=3;
  const bad=path.join(process.cwd(),"grid-project-invalid.json");fs.writeFileSync(bad,JSON.stringify(project));
  await page.locator("#sessionFile").setInputFiles(bad);
  await page.waitForFunction(()=>document.querySelector("#status")?.textContent?.includes("No se restauró"));
  assert.equal(await page.locator("#gridDivision").inputValue(),"8","Invalid snap division cannot replace project");
  delete project.manifestSha256;delete project.gridSnapOn;delete project.gridDivision;
  const legacy=path.join(process.cwd(),"grid-project-legacy.json");fs.writeFileSync(legacy,JSON.stringify(project));
  await page.locator("#sessionFile").setInputFiles(legacy);
  await page.waitForFunction(()=>document.querySelector("#status")?.textContent?.includes("Sesión restaurada"));
  assert.equal(await page.locator("#gridSnapOn").isChecked(),false,"Older sessions default snap off");
  assert.equal(await page.locator("#gridDivision").inputValue(),"16");
  assert.deepEqual(errors,[]);
  console.log("PASS grid: snap-on/off, correct BPM musical intervals, pasted source clip, keyboard undo/redo, validated project and legacy restore");
 }finally{await browser.close()}
})().catch(e=>{console.error(e);process.exit(1)});
