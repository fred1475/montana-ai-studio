'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path');
const {chromium}=require('playwright');
const rate=44100,frames=rate,amp=10000;
const tone=Buffer.alloc(44+frames*2);
tone.write('RIFF',0);tone.writeUInt32LE(tone.length-8,4);tone.write('WAVE',8);
tone.write('fmt ',12);tone.writeUInt32LE(16,16);tone.writeUInt16LE(1,20);
tone.writeUInt16LE(1,22);tone.writeUInt32LE(rate,24);tone.writeUInt32LE(rate*2,28);
tone.writeUInt16LE(2,32);tone.writeUInt16LE(16,34);
tone.write('data',36);tone.writeUInt32LE(frames*2,40);
for(let i=0;i<frames;i++)tone.writeInt16LE(Math.round(amp*Math.sin(Math.PI*2*440*i/rate)),44+i*2);
(async()=>{
 const browser=await chromium.launch({headless:true});
 try{
  const page=await browser.newPage({acceptDownloads:true}),errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto('http://127.0.0.1:8765/mixer-8.html');
  assert.equal(await page.locator('#alignMs0').count(),0,'Instrumental must not have voice sync control');
  assert.equal(await page.locator('#alignMs1').count(),1);
  await page.locator('#file1').setInputFiles({name:'voz-alinear.wav',mimeType:'audio/wav',buffer:tone});
  await page.waitForFunction(()=>document.querySelector('#label1')?.textContent?.includes('voz-alinear'));
  assert.equal(await page.locator('#downloadSource').isDisabled(),false);
  const [originalDownload]=await Promise.all([page.waitForEvent('download'),page.locator('#downloadSource').click()]);
  const originalPath=path.join(process.cwd(),'sync-rescued-original.wav');
  await originalDownload.saveAs(originalPath);
  assert.deepEqual(fs.readFileSync(originalPath),tone,'Source rescue must preserve exact original bytes');
  async function exportFrames(filename){
   const [download]=await Promise.all([page.waitForEvent('download'),page.locator('#export').click()]);
   const dest=path.join(process.cwd(),filename);await download.saveAs(dest);
   const out=fs.readFileSync(dest);
   return {out,frames:(out.length-44)/4};
  }
  await page.locator('#alignMs1').fill('100');
  assert.equal(await page.locator('#alignVal1').innerText(),'100 ms');
  const late=await exportFrames('sync-late.wav');
  assert(Math.abs(late.frames-rate*1.1)<4,'Positive 100ms should extend WAV by 100ms: '+late.frames);
  assert.equal(late.out.readInt16LE(44+1000*4),0,'Positive shift inserts leading silence');
  assert(Math.abs(late.out.readInt16LE(44+5000*4))>200,'Shifted tone should be audible');
  await page.locator('#alignMs1').fill('-100');
  const early=await exportFrames('sync-early.wav');
  assert(Math.abs(early.frames-rate*.9)<4,'Negative shift should trim 100ms at time zero: '+early.frames);
  await page.locator('#undoEdit').click();
  assert.equal(await page.locator('#alignMs1').inputValue(),'100','Undo can restore alignment');
  assert.equal(await page.locator('#alignVal1').innerText(),'100 ms');
  await page.locator('#redoEdit').click();
  assert.equal(await page.locator('#alignMs1').inputValue(),'-100','Redo can restore alignment');
  const [backup]=await Promise.all([page.waitForEvent('download'),page.locator('#saveSession').click()]);
  const backupPath=path.join(process.cwd(),'sync-session.json');await backup.saveAs(backupPath);
  const saved=JSON.parse(fs.readFileSync(backupPath,'utf8'));
  assert.equal(saved.tracks[1].alignMs,-100);
  assert(saved.tracks[1].data.length>1000,'Original source bytes embedded in session');
  await page.reload();
  await page.locator('#sessionFile').setInputFiles(backupPath);
  await page.waitForFunction(()=>document.querySelector('#status')?.textContent?.includes('Sesión restaurada'));
  assert.equal(await page.locator('#alignMs1').inputValue(),'-100');
  assert.equal(await page.locator('#downloadSource').isDisabled(),false);
  const [restoredSource]=await Promise.all([page.waitForEvent('download'),page.locator('#downloadSource').click()]);
  const restoredPath=path.join(process.cwd(),'sync-rescued-restored.wav');
  await restoredSource.saveAs(restoredPath);
  assert.deepEqual(fs.readFileSync(restoredPath),tone,'Restored source rescue still byte-exact');
  const restoredOutput=await exportFrames('sync-restored.wav');
  assert(Math.abs(restoredOutput.frames-rate*.9)<4);
  saved.tracks[1].alignMs=-700;
  const invalidPath=path.join(process.cwd(),'sync-invalid.json');
  fs.writeFileSync(invalidPath,JSON.stringify(saved));
  await page.locator('#sessionFile').setInputFiles(invalidPath);
  await page.waitForFunction(()=>document.querySelector('#status')?.textContent?.includes('No se restauró'));
  assert.equal(await page.locator('#alignMs1').inputValue(),'-100','Rejected invalid sync must preserve old project');
  assert.deepEqual(errors,[]);
  console.log('PASS: +-100 ms alignment changes actual PCM timing; undo/redo; exact source rescue; restored sessions; invalid session rejection.');
 }finally{await browser.close()}
})().catch(e=>{console.error(e);process.exit(1)});
