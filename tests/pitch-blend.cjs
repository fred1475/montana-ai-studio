'use strict';
/* Pure offline dry/wet mixing regression. No hardware or audio input. */
const assert=require('node:assert/strict');
const {blend}=require('../pitch-blend.js');
const dry=new Float32Array([.5,-.25,.1,0]),wet=new Float32Array([-.5,.75,.3,.8]);
const left=dry.slice(),right=wet.slice();
const zero=blend([dry],[wet],0)[0],all=blend([dry],[wet],100)[0];
assert.deepEqual(zero,dry);assert.deepEqual(all,wet);
assert.notStrictEqual(zero,dry);assert.notStrictEqual(all,wet);
const half=blend([dry],[wet],50)[0];
for(let i=0;i<dry.length;i++)assert(Math.abs(half[i]-(dry[i]+wet[i])/2)<1e-7);
const twenty=blend([dry],[wet],20)[0];
for(let i=0;i<dry.length;i++)assert(Math.abs(twenty[i]-(.8*dry[i]+.2*wet[i]))<1e-7);
const stereo=blend([dry,wet],[wet,dry],50);
assert.deepEqual(stereo[0],half);assert.deepEqual(stereo[1],half);
assert.deepEqual(dry,left,'Source must be immutable');assert.deepEqual(wet,right,'Wet must be immutable');
for(const amount of [-1,101,NaN,Infinity])assert.throws(()=>blend([dry],[wet],amount),/inválida/);
assert.throws(()=>blend([dry],[new Float32Array(2)],50),/incompatibles/);
assert.throws(()=>blend([],[],50),/inválida/);
const bad=dry.slice();bad[2]=NaN;
assert.throws(()=>blend([bad],[wet],50),/no finito/);
assert.throws(()=>blend([dry],[bad],0),/no finito/,'Validate both channels even in bypass');
assert.throws(()=>blend([new Float32Array(0)],[new Float32Array(0)],50),/Duración/);
const n=48000,signal=Float32Array.from({length:n},(_,i)=>.2*Math.sin(2*Math.PI*220*i/48000));
const backup=signal.slice();
const mixed=blend([signal],[Float32Array.from(signal,x=>-x)],50)[0];
assert(mixed.every(x=>Math.abs(x)<1e-7),'Simple equal-gain mix is intentionally phase-sensitive');
assert.deepEqual(signal,backup);
console.log('PASS pitch blend: 0/20/50/100%, stereo, original immutability, invalid PCM and phase warning case.');
