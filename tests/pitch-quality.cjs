'use strict';
/* Deterministic pitch sample QA, reference heuristics only. */
const assert=require('node:assert/strict');
const {analyze}=require('../pitch-quality.js');
const rate=44100,n=rate;
const tone=Float32Array.from({length:n},(_,i)=>.22*Math.sin(2*Math.PI*220*i/rate));
const frozen=tone.slice();
const unchanged=analyze([tone],[tone.slice()],rate);
assert.equal(unchanged.warnings.length,0);
assert(Math.abs(unchanged.metrics.rmsDeltaDb)<1e-8);
assert(Math.abs(unchanged.metrics.peakIncreaseDb)<1e-8);
assert.equal(unchanged.metrics.newLargeSteps,0);
assert.equal(unchanged.channels,1);
assert.equal(unchanged.stereo,null);
assert.equal(unchanged.metrics.highBandDeltaDb,0);
assert.equal(unchanged.metrics.dropoutWindowCount,0);
assert.equal(unchanged.metrics.firstDropoutSeconds,null);
for(const testRate of [44100,48000]){
 const frames=testRate;
 const source=Float32Array.from({length:frames},(_,i)=>.25*Math.sin(2*Math.PI*190*i/testRate));
 const treble=Float32Array.from({length:frames},(_,i)=>.25*Math.sin(2*Math.PI*5000*i/testRate));
 const sourceBackup=source.slice(),trebleBackup=treble.slice();
 const bypass=analyze([source],[source.slice()],testRate);
 assert(Math.abs(bypass.metrics.highBandDeltaDb)<1e-9);
 assert(!bypass.warnings.some(w=>w.id==='spectral_balance_shift'));
 const gain=analyze([source],[Float32Array.from(source,x=>x*.8)],testRate);
 assert(Math.abs(gain.metrics.highBandDeltaDb)<.001,'Gain should not change relative high-frequency energy');
 assert(!gain.warnings.some(w=>w.id==='spectral_balance_shift'));
 const bright=analyze([source],[treble],testRate);
 assert(bright.metrics.highBandDeltaDb>8);
 assert(bright.warnings.some(w=>w.id==='spectral_balance_shift'));
 const dull=analyze([treble],[source],testRate);
 assert(dull.metrics.highBandDeltaDb< -8);
 assert(dull.warnings.some(w=>w.id==='spectral_balance_shift'));
 const silentBand=analyze([new Float32Array(frames)],[new Float32Array(frames)],testRate);
 assert.equal(silentBand.metrics.highBandDeltaDb,null);
 assert(!silentBand.warnings.some(w=>w.id==='spectral_balance_shift'));
 const nearSilent=Float32Array.from(source,x=>x*.000004);
 const quietInput=analyze([nearSilent],[nearSilent],testRate);
 assert.equal(quietInput.metrics.highBandDeltaDb,null,'Near-silence must not have a trusted spectrum');
 const quietOutput=analyze([source],[nearSilent],testRate);
 assert.equal(quietOutput.metrics.highBandDeltaDb,null);
 assert(quietOutput.warnings.some(w=>w.id==='signal_loss'));
 assert(!quietOutput.warnings.some(w=>w.id==='spectral_balance_shift'));

 const dropped=source.slice(),naturalPause=source.slice();
 for(let i=Math.floor(testRate*.37);i<Math.floor(testRate*.58);i++){
  dropped[i]=0;naturalPause[i]=0;
 }
 const dropout=analyze([source],[dropped],testRate);
 assert(dropout.metrics.dropoutWindowCount>=4);
 assert(dropout.metrics.firstDropoutSeconds>=.35&&dropout.metrics.firstDropoutSeconds<=.4);
 assert(dropout.warnings.some(w=>w.id==='local_dropouts'));
 const intendedPause=analyze([naturalPause],[naturalPause.slice()],testRate);
 assert.equal(intendedPause.metrics.dropoutWindowCount,0);
 assert(!intendedPause.warnings.some(w=>w.id==='local_dropouts'));
 const uniformGain=analyze([source],[Float32Array.from(source,x=>x*.3)],testRate);
 assert.equal(uniformGain.metrics.dropoutWindowCount,0);
 const allMissing=analyze([source],[new Float32Array(frames)],testRate);
 assert.equal(allMissing.metrics.dropoutWindowCount,0);
 assert(allMissing.warnings.some(w=>w.id==='signal_loss'));
 const doubleStereo=analyze([source,source],[source,dropped],testRate);
 assert(doubleStereo.metrics.dropoutWindowCount>=4);
 assert(doubleStereo.warnings.some(w=>w.id==='local_dropouts'));
 assert.deepEqual(dropped.slice(0,Math.floor(testRate*.30)),source.slice(0,Math.floor(testRate*.30)));
 assert.deepEqual(source,sourceBackup);
 assert.deepEqual(treble,trebleBackup);
}
const stereo=analyze([tone,tone],[tone.slice(),tone.slice()],rate);
assert.equal(stereo.channels,2);assert.equal(stereo.frames,n);assert.deepEqual(stereo.warnings,[]);
assert(stereo.stereo&&Math.abs(stereo.stereo.source.correlation-1)<1e-6);
assert(Math.abs(stereo.stereo.output.correlation-1)<1e-6);
const inverted=Float32Array.from(tone,v=>-v);
const phaseChanged=analyze([tone,tone],[tone,inverted],rate);
assert(phaseChanged.stereo.output.correlation<-.99);
assert(phaseChanged.warnings.some(w=>w.id==='stereo_coherence_change'));
const antiphaseSame=analyze([tone,inverted],[tone,inverted],rate);
assert(antiphaseSame.stereo.source.correlation<-.99);
assert.deepEqual(antiphaseSame.warnings,[]);
const softerRight=Float32Array.from(tone,v=>v*.4);
const balanceChanged=analyze([tone,tone],[tone,softerRight],rate);
assert(balanceChanged.warnings.some(w=>w.id==='stereo_balance_change'));
assert(balanceChanged.stereo.output.balanceDb>7.9);
const emptyRight=new Float32Array(n);
const emptySide=analyze([tone,emptyRight],[tone,emptyRight],rate);
assert.equal(emptySide.stereo.source.correlation,null);
assert.equal(emptySide.stereo.output.balanceDb,null);
assert(!emptySide.warnings.some(w=>w.id.startsWith('stereo_')));
const louder=Float32Array.from(tone,x=>x*2.7);
const boost=analyze([tone],[louder],rate);
assert(boost.metrics.rmsDeltaDb>8&&boost.warnings.some(x=>x.id==='rms_change'));
const clipped=Float32Array.from(tone,x=>x*6);
const clipping=analyze([tone],[clipped],rate);
assert(clipping.warnings.some(x=>x.id==='sample_clip'));
const almost=Float32Array.from(tone,x=>x*4.5);
const headroom=analyze([tone],[almost],rate);
assert(headroom.warnings.some(x=>x.id==='low_headroom'));
const jump=tone.slice();
jump[rate/2]=-.95;
const snap=analyze([tone],[jump],rate);
assert(snap.metrics.newLargeSteps>=1);
assert(snap.warnings.some(x=>x.id==='new_steps'));
const silent=analyze([tone],[new Float32Array(n)],rate);
assert(silent.warnings.some(x=>x.id==='signal_loss'));
assert(silent.warnings.some(x=>x.id==='rms_change')===false,'Silent endpoint has no finite dB difference');
const zeros=new Float32Array(n);
const quiet=analyze([zeros],[zeros],rate);
assert.equal(quiet.metrics.sourcePeakDbfs,null);
assert.equal(quiet.metrics.outputRmsDbfs,null);
assert.deepEqual(quiet.warnings,[]);
for(const invalid of [0,4800,Infinity])assert.throws(()=>analyze([tone],[tone],invalid),/QA vocal inválidos/);
assert.throws(()=>analyze([tone],[new Float32Array(10)],rate),/incompatibles/);
assert.throws(()=>analyze([],[],rate),/QA vocal inválidos/);
const bad=tone.slice();bad[40000]=NaN;
assert.throws(()=>analyze([bad],[tone],rate),/no finita/);
const infinity=tone.slice();infinity[1]=Infinity;
assert.throws(()=>analyze([tone],[infinity],rate),/no finita/);
assert.deepEqual(tone,frozen,'QA never modifies the original');
assert.equal(unchanged.qualification.includes('no certificación'),true);
console.log('PASS pitch QA: dropout windows and spectral shift 44.1/48k, stereo phase/balance, bypass, two channels, RMS gain, peak headroom, sample clipping, new discontinuity, silence, invalid PCM, immutable audio.');
